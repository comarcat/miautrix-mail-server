import { useEffect, useState } from 'react';
import { webmailClient } from './WebmailApiClient';

type Script = { id: string; name: string; content: string; isActive?: boolean; is_active?: boolean };
const isActive = (script: Script) => Boolean(script.isActive ?? script.is_active);

export function vacationScript(subject: string, message: string, days: number): string {
  const quote = (value: string) => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  const body = message.replace(/\\/g, '\\\\').replace(/"""/g, '\\"""');
  return `require ["vacation"];\nvacation :days ${Math.max(1, Math.min(30, Math.trunc(days) || 7))} :subject ${quote(subject || 'Out of office')} :mime text:  # generated by Settings\n${body}\n.\n;`;
}

export function SieveScriptSettings({ mailboxId }: { mailboxId: string }) {
  const [scripts, setScripts] = useState<Script[]>([]);
  const [name, setName] = useState('My filters');
  const [scriptId, setScriptId] = useState<string | undefined>();
  const [content, setContent] = useState('keep;');
  const [error, setError] = useState('');
  const [vacationOn, setVacationOn] = useState(false);
  const [subject, setSubject] = useState('Out of office');
  const [message, setMessage] = useState('I am away and will reply when I return.');
  const [days, setDays] = useState(7);
  const refresh = async () => setScripts(await webmailClient.getSieveScripts(mailboxId));
  useEffect(() => { void refresh().catch(() => setError('Could not load filters.')); }, [mailboxId]);
  const save = async (activate = false) => {
    setError('');
    try {
      const saved = await webmailClient.saveSieveScript(mailboxId, name, content, scriptId);
      setScriptId(saved.id);
      if (activate) await webmailClient.setSieveScriptActive(mailboxId, saved.id, true);
      await refresh();
    } catch (e: any) {
      const details = e?.details ?? e?.data?.details ?? {};
      const line = details.line?.[0] ?? details.line;
      const column = details.column?.[0] ?? details.column;
      setError(line && column ? `Line ${line}, column ${column}: ${e.message}` : e?.message ?? 'Could not save script.');
    }
  };
  const toggleVacation = async (enabled: boolean) => {
    setVacationOn(enabled);
    if (!enabled) return;
    setName('Out of office');
    setContent(vacationScript(subject, message, days));
  };
  const saveVacation = async () => {
    const vacation = scripts.find(item => item.name === 'Out of office');
    const generated = vacationScript(subject, message, days);
    try {
      const saved = await webmailClient.saveSieveScript(mailboxId, 'Out of office', generated, vacation?.id);
      await webmailClient.setSieveScriptActive(mailboxId, saved.id, vacationOn);
      await refresh();
    } catch (e: any) { setError(e?.message ?? 'Could not save out-of-office settings.'); }
  };
  return <section className="card" aria-label="Sieve filters" style={{ marginBottom: 24 }}>
    <h3>Filters</h3>
    <div>{scripts.map(script => <div key={script.id} style={{ display: 'flex', gap: 8, alignItems: 'center' }}>
      <label><input type="checkbox" checked={isActive(script)} onChange={async e => { await webmailClient.setSieveScriptActive(mailboxId, script.id, e.target.checked); await refresh(); }} /> {script.name}</label>
      <button type="button" onClick={() => { setScriptId(script.id); setName(script.name); setContent(script.content); }}>Edit</button>
      <button type="button" onClick={async () => { await webmailClient.deleteSieveScript(mailboxId, script.id); await refresh(); }}>Delete</button>
    </div>)}</div>
    <label>Script name <input value={name} onChange={e => setName(e.target.value)} /></label>
    <label> Sieve script <textarea aria-label="Sieve script" rows={10} value={content} onChange={e => setContent(e.target.value)} /></label>
    <button type="button" onClick={() => void save()}>Save script</button> <button type="button" onClick={() => void save(true)}>Save and activate</button>
    {error && <div role="alert">{error}</div>}
    <hr /><h4>Out of office</h4>
    <label><input aria-label="Out of office" type="checkbox" checked={vacationOn} onChange={e => void toggleVacation(e.target.checked)} /> On</label>
    <label>Subject <input value={subject} onChange={e => setSubject(e.target.value)} /></label>
    <label>Message <textarea value={message} onChange={e => setMessage(e.target.value)} /></label>
    <label>Days between replies <input type="number" min={1} max={30} value={days} onChange={e => setDays(Number(e.target.value))} /></label>
    <button type="button" onClick={() => void saveVacation()}>Save out-of-office</button>
  </section>;
}

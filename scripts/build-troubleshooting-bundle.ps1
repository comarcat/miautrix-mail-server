[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$manualPath = Join-Path $repoRoot 'docs/TROUBLESHOOTING.md'
$zipPath = Join-Path $repoRoot 'docs/TROUBLESHOOTING-scripts.zip'
$marker = '<!-- APPENDIX:BEGIN (generated by scripts/build-troubleshooting-bundle.ps1; do not edit below) -->'
$scriptFiles = @(
    @{ Path = 'scripts/deploy-release.ps1'; Language = 'powershell' },
    @{ Path = 'scripts/lxc-release.sh'; Language = 'bash' },
    @{ Path = 'scripts/lxc-prepare-storage.sh'; Language = 'bash' },
    @{ Path = 'scripts/cleanup-test-tenants.sh'; Language = 'bash' },
    @{ Path = 'scripts/imap-external-validation.py'; Language = 'python' }
)

function Get-LfText([string]$Path) {
    $text = [System.IO.File]::ReadAllText($Path, [System.Text.Encoding]::UTF8)
    return ($text -replace "`r`n", "`n" -replace "`r", "`n")
}

function Get-Appendix {
    $sections = [System.Collections.Generic.List[string]]::new()
    $sections.Add('## Appendix A — Script reference')
    $sections.Add('')
    foreach ($script in $scriptFiles) {
        $fullPath = Join-Path $repoRoot ($script.Path.Replace('/', [IO.Path]::DirectorySeparatorChar))
        if (-not (Test-Path -LiteralPath $fullPath -PathType Leaf)) {
            throw "Required script is missing: $($script.Path)"
        }

        $text = Get-LfText $fullPath
        foreach ($line in ($text -split "`n")) {
            if ($line -match '(?i)(?<![A-Za-z0-9_])Password\s*=(?!\s*os\.environ\.get)|-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----') {
                throw "Refusing to publish a script line that looks secret-bearing: $($script.Path)"
            }
        }

        $sha256 = (Get-FileHash -LiteralPath $fullPath -Algorithm SHA256).Hash.ToLowerInvariant()
        $sections.Add("### ``$($script.Path)``")
        $sections.Add('')
        $sections.Add("SHA-256: ``$sha256``")
        $sections.Add('')
        $sections.Add("````$($script.Language)")
        $sections.Add($text.TrimEnd("`n"))
        $sections.Add('````')
        $sections.Add('')
    }
    return ($sections -join "`n").TrimEnd("`n") + "`n"
}

function New-DeterministicZipBytes {
    $memory = [System.IO.MemoryStream]::new()
    try {
        $archive = [System.IO.Compression.ZipArchive]::new(
            $memory,
            [System.IO.Compression.ZipArchiveMode]::Create,
            $true
        )
        try {
            foreach ($script in $scriptFiles) {
                $sourcePath = Join-Path $repoRoot ($script.Path.Replace('/', [IO.Path]::DirectorySeparatorChar))
                $text = Get-LfText $sourcePath
                $entry = $archive.CreateEntry($script.Path, [System.IO.Compression.CompressionLevel]::Optimal)
                $entry.LastWriteTime = [DateTimeOffset]::new(1980, 1, 1, 0, 0, 0, [TimeSpan]::Zero)
                $entry.ExternalAttributes = 0
                $entryStream = $entry.Open()
                try {
                    $bytes = [System.Text.UTF8Encoding]::new($false).GetBytes($text)
                    $entryStream.Write($bytes, 0, $bytes.Length)
                }
                finally {
                    $entryStream.Dispose()
                }
            }
        }
        finally {
            $archive.Dispose()
        }
        return ,$memory.ToArray()
    }
    finally {
        $memory.Dispose()
    }
}

if ($PSVersionTable.PSVersion.Major -lt 7) {
    throw 'PowerShell 7 or later is required.'
}

Add-Type -AssemblyName System.IO.Compression
$appendix = Get-Appendix
$manual = [System.IO.File]::ReadAllText($manualPath, [System.Text.Encoding]::UTF8)
$markerMatch = [regex]::Match($manual, '(?m)^<!-- APPENDIX:BEGIN \(generated by scripts/build-troubleshooting-bundle\.ps1; do not edit below\) -->\r?$')
if ($Check -and -not $markerMatch.Success) {
    Write-Error "Appendix marker is missing from $manualPath"
    exit 1
}
if ($markerMatch.Success) {
    $prefix = $manual.Substring(0, $markerMatch.Index)
}
else {
    $prefix = $manual.TrimEnd("`r", "`n")
}
$expectedManual = $prefix.TrimEnd("`r", "`n") + "`n" + $marker + "`n" + $appendix
$expectedZip = New-DeterministicZipBytes

if ($Check) {
    $manualCurrent = [System.IO.File]::ReadAllText($manualPath, [System.Text.Encoding]::UTF8)
    $zipCurrent = if (Test-Path -LiteralPath $zipPath -PathType Leaf) { [System.IO.File]::ReadAllBytes($zipPath) } else { [byte[]]@() }
    $manualMatches = $manualCurrent -ceq $expectedManual
    $zipMatches = [System.Convert]::ToBase64String($zipCurrent) -ceq [System.Convert]::ToBase64String($expectedZip)
    if (-not $manualMatches -or -not $zipMatches) {
        if (-not $manualMatches) { Write-Error 'Generated appendix is out of date.' }
        if (-not $zipMatches) { Write-Error 'Troubleshooting script ZIP is out of date.' }
        exit 1
    }
    Write-Output 'Troubleshooting appendix and ZIP are up to date.'
    exit 0
}

[System.IO.File]::WriteAllText($manualPath, $expectedManual, [System.Text.UTF8Encoding]::new($false))
[System.IO.File]::WriteAllBytes($zipPath, $expectedZip)
Write-Output "Generated $manualPath and $zipPath"
